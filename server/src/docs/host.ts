// docs.fluxpkg.dev:
//   /                       index of packages
//   /<id>/                  302 to the newest non-yanked version
//   /<id>/<version>/<path>  a generated page (empty path: index.html)

import type { Ctx, Env } from "../env";
import { CACHE_CONTROL, ETAG, cached } from "../lib/cache";
import { LATEST_ORDER, search } from "../lib/db";
import { trimSlash } from "../lib/metadata";
import { canonicalize, isValidId } from "../lib/version";
import { html, plainPage } from "../web/html";
import { FdocError } from "./fdoc";
import { FDOC_FAILURE, contentType, docsCsp, docsPrefix, enqueueDocs, generateDocs, markFailed, onDemandBytes, pathHash, storeDocs } from "./generate";

/** Retry-After of the "being generated" page. */
const RETRY_SECONDS = 30;

function docsBase(env: Env): string {
  return trimSlash(env.DOCS_URL);
}

function redirect(location: string, cacheControl: string): Response {
  return new Response(null, { status: 302, headers: { Location: location, "Cache-Control": cacheControl } });
}

function notFoundPage(what: string): Response {
  return plainPage("Not found", html`<h1>Not found</h1><p>${what}</p><p><a href="/">All packages</a></p>`, 404, CACHE_CONTROL.page);
}

/** Splits and decodes the path; null when a segment is unsafe. */
function segments(pathname: string): string[] | null {
  const parts = pathname.split("/").slice(1);
  const out: string[] = [];
  for (const [i, raw] of parts.entries()) {
    let s: string;
    try {
      s = decodeURIComponent(raw);
    } catch {
      return null;
    }
    if (s === "" && i !== parts.length - 1) return null;
    if (s === "." || s === ".." || s.includes("\\") || s.includes("/") || /[\u0000-\u001f]/.test(s)) return null;
    out.push(s);
  }
  return out;
}

/** Handles a request for the docs host; `pathname` is relative to the docs root. */
export async function docsFetch(request: Request, pathname: string, env: Env, ctx: Ctx): Promise<Response> {
  if (request.method !== "GET" && request.method !== "HEAD") {
    return new Response("method not allowed", { status: 405, headers: { Allow: "GET, HEAD" } });
  }
  const segs = segments(pathname);
  if (!segs) return notFoundPage("That is not a documentation path.");
  const [id, version, ...rest] = segs;

  if (!id) return cached(request, ctx, () => indexPage(env));
  if (!isValidId(id)) return notFoundPage(`There is no package \`${id}\`.`);
  if (version === undefined) return redirect(`${docsBase(env)}/${id}/`, CACHE_CONTROL.docsRedirect);
  if (version === "") return latestRedirect(env, id);

  const canonical = canonicalize(version);
  if (!canonical) return notFoundPage(`\`${version}\` is not a version.`);
  if (canonical !== version || rest.length === 0) {
    return redirect(`${docsBase(env)}/${id}/${canonical}/${rest.map(encodeURIComponent).join("/")}`, CACHE_CONTROL.docsRedirect);
  }
  let path = rest.join("/");
  if (path === "" || path.endsWith("/")) path += "index.html";
  // 404s are cached briefly so missing pages cannot each cost a generation.
  return cached(request, ctx, () => servePage(env, ctx, id, version, path), { variant: env.FDOC_VERSION, cacheNotFound: true });
}

async function indexPage(env: Env): Promise<Response> {
  const all = await search(env.DB, "", 1, 10_000);
  const items = all.packages.map(
    (p) => html`<li><a href="${docsBase(env)}/${p.id}/${p.version}/"><strong>${p.name}</strong></a> <code>${p.id}</code> <span class="muted">${p.version}</span>
      ${p.summary ? html`<div class="muted">${p.summary}</div>` : ""}</li>`,
  );
  const body = html`<h1>Package documentation</h1>
    <p class="muted">Generated by fdoc ${env.FDOC_VERSION} for every version on <a href="${trimSlash(env.SITE_URL)}/">fluxpkg.dev</a>.</p>
    ${items.length > 0 ? html`<ul class="packages">${items}</ul>` : html`<p>No packages yet.</p>`}`;
  return plainPage("Package documentation", body, 200, CACHE_CONTROL.page);
}

async function latestRedirect(env: Env, id: string): Promise<Response> {
  const row = await env.DB.prepare(`SELECT version FROM versions WHERE package_id = ? AND yanked = 0 ORDER BY ${LATEST_ORDER} LIMIT 1`)
    .bind(id)
    .first<{ version: string }>();
  if (!row) return notFoundPage(`There is no package \`${id}\` with a version that is not yanked.`);
  return redirect(`${docsBase(env)}/${id}/${row.version}/`, CACHE_CONTROL.docsRedirect);
}

async function pageResponse(env: Env, path: string, body: ReadableStream | string, sha256: string, csp: string | undefined): Promise<Response> {
  const headers: Record<string, string> = {
    "Content-Type": contentType(path),
    "Cache-Control": CACHE_CONTROL.docs,
    ETag: ETAG.docs(env.FDOC_VERSION, sha256, await pathHash(path)),
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
  };
  if (path.endsWith(".html")) headers["Content-Security-Policy"] = csp || (await docsCsp());
  return new Response(body, { status: 200, headers });
}

async function servePage(env: Env, ctx: Ctx, id: string, version: string, path: string): Promise<Response> {
  const obj = await env.DOCS.get(docsPrefix(env, id, version) + path);
  if (obj) return pageResponse(env, path, obj.body, obj.customMetadata?.sha256 ?? "", obj.customMetadata?.csp);

  // Does the version exist, and are its docs done for this fdoc?
  const row = await env.DB.prepare("SELECT sha256, docs_status, docs_version, docs_error FROM versions WHERE package_id = ? AND version = ?")
    .bind(id, version)
    .first<{ sha256: string; docs_status: string; docs_version: string | null; docs_error: string | null }>();
  if (!row) return notFoundPage(`There is no version ${version} of \`${id}\`.`);
  const current = row.docs_version === env.FDOC_VERSION;
  // Ready means the page does not exist, unless R2 lifecycle expired the whole generation.
  if (current && row.docs_status === "ready" && (path === "index.html" ? false : await env.DOCS.head(docsPrefix(env, id, version) + "index.html"))) {
    return notFoundPage(`The documentation of ${id} ${version} has no page \`${path}\`.`);
  }
  if (current && row.docs_status === "failed" && row.docs_error?.startsWith(FDOC_FAILURE)) return failedPage(id, version, row.docs_error);

  // A generation in this isolate, still being stored, already showed the page does not exist.
  const known = generated.get(`${env.FDOC_VERSION}/${id}/${version}`);
  if (known && !known.has(path)) return notFoundPage(`The documentation of ${id} ${version} has no page \`${path}\`.`);

  // On demand: after an fdoc deploy, or when the queue job has not run or failed.
  let gen;
  try {
    gen = await generateDocs(env, id, version, onDemandBytes(env));
  } catch (e) {
    if (!(e instanceof FdocError)) throw e;
    ctx.waitUntil(markFailed(env, id, version, e.message, true).catch(() => {}));
    return failedPage(id, version, e.message);
  }
  if (gen.status === "missing") return notFoundPage(`There is no version ${version} of \`${id}\`.`);
  if (gen.status === "too_large") {
    // At most one queued job per version and fdoc until it ages out.
    ctx.waitUntil(enqueueDocs(env, id, version).catch((e) => console.error("enqueue failed", e)));
    return plainPage(
      "Generating documentation",
      html`<h1>${id} ${version}</h1><p>The documentation is being generated. This page will work in a minute; try again shortly.</p>`,
      202,
      CACHE_CONTROL.noStore,
      { "Retry-After": String(RETRY_SECONDS) },
    );
  }
  remember(`${env.FDOC_VERSION}/${id}/${version}`, new Set(gen.pages.map((p) => p.path)));
  ctx.waitUntil(storeDocs(env, id, version, gen.sha256, gen.pages).catch((e) => console.error(`storing docs of ${id} ${version} failed`, e)));
  const page = gen.pages.find((p) => p.path === path);
  if (!page) return notFoundPage(`The documentation of ${id} ${version} has no page \`${path}\`.`);
  return pageResponse(env, path, page.content, gen.sha256, await docsCsp());
}

/** Page paths of recent on-demand generations in this isolate, newest last. */
const generated = new Map<string, Set<string>>();
const GENERATED_ENTRIES = 64;

function remember(key: string, paths: Set<string>): void {
  generated.delete(key);
  generated.set(key, paths);
  while (generated.size > GENERATED_ENTRIES) generated.delete(generated.keys().next().value!);
}

function failedPage(id: string, version: string, error: string | null): Response {
  return plainPage(
    "Documentation failed",
    html`<h1>${id} ${version}</h1><p>fdoc could not generate the documentation of this version.</p><pre>${error ?? ""}</pre>`,
    500,
    CACHE_CONTROL.noStore,
  );
}
