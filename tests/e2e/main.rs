fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/flux-ce")
}

fn write(p: &Path, s: &str) {
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, s).unwrap();
}

/// The fixtures' versions written out as X.Y.Z, as publishing requires.
fn three_component_versions(flux: &Path) {
    for entry in std::fs::read_dir(flux.join("packages")).unwrap() {
        let spec = entry.unwrap().path().join("packagespec.lua");
        let s = read(&spec)
            .replace("s.version     = '1.0'\n", "s.version     = '1.0.0'\n")
            .replace("'20211019'", "'20211019.0.0'");
        std::fs::write(&spec, s).unwrap();
    }
}

/// A standalone package project with binary modules in a git-ignored build
/// folder, like gmsv_file's checkout.
fn binary_package(dir: &Path) {
    write(
        &dir.join("packagespec.lua"),
        "Package:describe(function(s)\n  s.id          = 'gmsv_demo'\n  s.name        = 'Demo module'\n  s.version     = '1.0.0'\n  s.summary     = 'A binary module.'\n  s.license     = 'MIT'\n  s.serverside  = true\n  s.binaries    = 'build/bin'\nend)\n",
    );
    write(&dir.join(".gitignore"), "build/\n");
    write(&dir.join(".fpkgignore"), "src/\n");
    write(&dir.join("src/main.cpp"), "int main() {}\n");
    write(&dir.join("build/obj/main.o"), "object");
    write(&dir.join("build/bin/gmsv_demo_linux64.dll"), "linux64");
    write(&dir.join("build/bin/gmsv_demo_win64.dll"), "win64");
    write(
        &dir.join("build/bin/LICENSES.txt"),
        "licenses of the linked libraries\n",
    );
    write(
        &dir.join("content/materials/demo/x.vmt"),
        "\"VertexLitGeneric\" {}\n",
    );
}

/// Makes `author()` deterministic: git reads user.name from the environment.
const AUTHOR: [(&str, &str); 3] = [
    ("GIT_CONFIG_COUNT", "1"),
    ("GIT_CONFIG_KEY_0", "user.name"),
    ("GIT_CONFIG_VALUE_0", "Test Author"),
];

fn find<'a>(list: &'a serde_json::Value, id: &str) -> &'a serde_json::Value {
    list.as_array()
        .unwrap()
        .iter()
        .find(|p| p["id"] == id)
        .unwrap_or_else(|| panic!("no {id} in {list}"))
}

