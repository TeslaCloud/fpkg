//! End to end: the flux-ce fixtures checked, locked, packed and published to a
//! registry, then installed and verified from it by a second project.

#[path = "../support/mock_registry.rs"]
mod mock_registry;

use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

struct Env {
    _tmp: tempfile::TempDir,
    root: PathBuf,
}

impl Env {
    fn new() -> Env {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().canonicalize().unwrap();
        Env { _tmp: tmp, root }
    }

    fn registry_url(&self) -> String {
        format!("file://{}/registry/", self.root.display())
    }

    fn fpkg(&self, project: &Path, args: &[&str]) -> Output {
        self.fpkg_with(project, args, &[], None)
    }

    fn fpkg_with(&self, project: &Path, args: &[&str], vars: &[(&str, &str)], stdin: Option<&str>) -> Output {
        let mut c = Command::new(env!("CARGO_BIN_EXE_fpkg"));
        c.arg("--project").arg(project).args(args).current_dir(&self.root);
        c.env("FPKG_CACHE_DIR", self.root.join("cache"))
            .env("FPKG_CONFIG_DIR", self.root.join("config"))
            .env("FPKG_REGISTRY", self.registry_url())
            .env("NO_COLOR", "1")
            .env_remove("FPKG_TOKEN")
            .env_remove("SOURCE_DATE_EPOCH")
            .env_remove("FPKG_OFFLINE");
        for (k, v) in vars {
            c.env(k, v);
        }
        c.stdin(Stdio::piped()).stdout(Stdio::piped()).stderr(Stdio::piped());
        let mut child = c.spawn().unwrap();
        let mut input = child.stdin.take().unwrap();
        if let Some(s) = stdin {
            input.write_all(s.as_bytes()).unwrap();
        }
        drop(input);
        child.wait_with_output().unwrap()
    }
}

fn text(o: &Output) -> String {
    format!("{}{}", String::from_utf8_lossy(&o.stdout), String::from_utf8_lossy(&o.stderr))
}

#[track_caller]
fn ok(o: Output) -> Output {
    assert!(o.status.success(), "expected success, got {:?}:\n{}", o.status.code(), text(&o));
    o
}

#[track_caller]
fn code(o: Output, want: i32) -> Output {
    assert_eq!(o.status.code(), Some(want), "expected exit {want}:\n{}", text(&o));
    o
}

fn copy_dir(from: &Path, to: &Path) {
    for entry in walkdir::WalkDir::new(from) {
        let entry = entry.unwrap();
        let dest = to.join(entry.path().strip_prefix(from).unwrap());
        if entry.file_type().is_dir() {
            std::fs::create_dir_all(&dest).unwrap();
        } else {
            std::fs::copy(entry.path(), &dest).unwrap();
        }
    }
}

fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

fn json(o: &Output) -> serde_json::Value {
    serde_json::from_slice(&o.stdout).unwrap_or_else(|e| panic!("not JSON ({e}):\n{}", text(o)))
}

#[test]
fn flux_ce_to_registry_to_schema() {
    let env = Env::new();
    let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/flux-ce");
    let flux = env.root.join("flux-ce");
    copy_dir(&fixtures, &flux);

    // check, list, tree on the copy.
    let o = ok(env.fpkg(&flux, &["check"]));
    assert!(text(&o).contains("17 checked, 0 with errors"), "{}", text(&o));
    let o = ok(env.fpkg(&flux, &["--json", "list"]));
    assert_eq!(json(&o).as_array().unwrap().len(), 16);

    // lock: 16 workspace entries, byte-stable.
    ok(env.fpkg(&flux, &["lock"]));
    let lock = read(&flux.join("fpkg.lock"));
    assert!(lock.starts_with("# Generated by fpkg. Do not edit by hand.\nversion = 1\n"), "{lock}");
    assert_eq!(lock.matches("[[package]]").count(), 16);
    assert_eq!(lock.matches("source = \"workspace\"").count(), 16);
    assert!(lock.contains("id = \"bolt\"\nversion = \"1.0.0\"\nsource = \"workspace\"\ndependencies = [\"active_record\", \"active_ui\", \"cami\", \"flow\"]\n"), "{lock}");
    ok(env.fpkg(&flux, &["lock"]));
    assert_eq!(read(&flux.join("fpkg.lock")), lock);
    let o = ok(env.fpkg(&flux, &["--json", "tree"]));
    assert_eq!(json(&o)["dependencies"].as_array().unwrap().len(), 15);

    // pack every package, twice: same path, same sha256.
    let archives = env.root.join("archives");
    let ids: Vec<String> = json(&ok(env.fpkg(&flux, &["--json", "list"])))
        .as_array()
        .unwrap()
        .iter()
        .map(|p| p["id"].as_str().unwrap().to_string())
        .collect();
    for id in &ids {
        let a = json(&ok(env.fpkg(&flux, &["--json", "pack", id, "-o", archives.to_str().unwrap()])));
        let b = json(&ok(env.fpkg(&flux, &["--json", "pack", id, "-o", archives.to_str().unwrap()])));
        assert_eq!(a["sha256"], b["sha256"], "{id}");
        assert!(Path::new(a["path"].as_str().unwrap()).is_file());
        assert_eq!(a["members"][0]["path"], format!("{id}/packagespec.lua"));
    }
    let o = ok(env.fpkg(&flux, &["pack", "fontawesome", "--list", "-o", archives.to_str().unwrap()]));
    assert!(text(&o).contains("fontawesome/lib/cl_icons.lua"), "{}", text(&o));
    // Without an id, outside packages/<id>/, pack needs a human.
    code(env.fpkg(&flux, &["pack"]), 2);

    // publish --all refuses two-component versions ...
    let o = code(env.fpkg(&flux, &["publish", "--all", "--yes"]), 1);
    assert!(text(&o).contains("three-component version"), "{}", text(&o));
    // ... so write them out as X.Y.Z, then bootstrap.
    for id in &ids {
        let spec = flux.join("packages").join(id).join("packagespec.lua");
        let s = read(&spec).replace("s.version     = '1.0'\n", "s.version     = '1.0.0'\n").replace("'20211019'", "'20211019.0.0'");
        std::fs::write(&spec, s).unwrap();
    }
    ok(env.fpkg(&flux, &["publish", "--all", "--dry-run"]));
    assert!(!env.root.join("registry/packages").exists(), "a dry run uploads nothing");
    let o = ok(env.fpkg(&flux, &["publish", "--all", "--yes"]));
    let out = text(&o);
    for id in &ids {
        assert!(env.root.join(format!("registry/packages/{id}.json")).is_file(), "{id} not published:\n{out}");
    }
    // Topological: sfs before cable, every dependency of bolt before bolt.
    let pos = |id: &str| out.find(&format!("Published {id} ")).unwrap_or_else(|| panic!("{id}:\n{out}"));
    assert!(pos("sfs") < pos("cable"));
    for dep in ["flow", "active_record", "active_ui", "cami"] {
        assert!(pos(dep) < pos("bolt"), "{dep} after bolt:\n{out}");
    }
    let o = ok(env.fpkg(&flux, &["publish", "--all", "--yes"]));
    assert!(text(&o).contains("nothing to publish"), "{}", text(&o));
    let o = code(env.fpkg(&flux, &["publish", "sfs", "--yes"]), 1);
    assert!(text(&o).contains("already on"), "{}", text(&o));
    // The registry has what pack produced.
    let doc: serde_json::Value = serde_json::from_str(&read(&env.root.join("registry/packages/cable.json"))).unwrap();
    assert_eq!(doc["latest"], "1.0.0");
    assert_eq!(doc["versions"]["1.0.0"]["dependencies"][0]["id"], "sfs");

    // Registry reads.
    let o = ok(env.fpkg(&flux, &["--json", "search", "serial"]));
    assert_eq!(json(&o)["packages"][0]["id"], "sfs");
    let o = ok(env.fpkg(&flux, &["--json", "info", "cable@1.0.0"]));
    assert_eq!(json(&o)["dist"]["sha256"].as_str().unwrap().len(), 64);
    let o = ok(env.fpkg(&flux, &["--json", "info", "fontawesome"]));
    assert_eq!(json(&o)["resources"].as_array().unwrap().len(), 3, "local info shows recorded resources");
    let o = ok(env.fpkg(&flux, &["--json", "owner", "list", "sfs"]));
    assert_eq!(json(&o).as_array().unwrap().len(), 1);

    // A schema that consumes sfs and cable from the registry.
    let schema = env.root.join("schema");
    ok(env.fpkg(&schema, &["init"]));
    let spec = schema.join("packagespec.lua");
    let s = read(&spec).replace("end)\n", "\n  s.depends('sfs', '~> 7.0')\n  s.depends 'cable'\nend)\n");
    std::fs::write(&spec, s).unwrap();
    ok(env.fpkg(&schema, &["check"]));
    code(env.fpkg(&schema, &["install", "--locked"]), 3);
    let o = ok(env.fpkg(&schema, &["install"]));
    assert!(text(&o).contains("2 added, 0 updated, 0 removed, 0 unchanged"), "{}", text(&o));
    let lock = read(&schema.join("fpkg.lock"));
    assert_eq!(lock.matches("source = \"registry+file://").count(), 2, "{lock}");
    assert_eq!(lock.matches("sha256 = ").count(), 2);
    assert!(schema.join("packages/sfs/lib/install.lua").is_file());
    let marker = read(&schema.join("packages/cable/.fpkg.toml"));
    assert!(marker.contains("id = \"cable\"") && marker.contains("version = \"1.0.0\"") && marker.contains("installed_at"), "{marker}");
    ok(env.fpkg(&schema, &["verify"]));
    let o = ok(env.fpkg(&schema, &["install", "--locked"]));
    assert!(text(&o).contains("0 added, 0 updated, 0 removed, 2 unchanged"), "{}", text(&o));
    let o = ok(env.fpkg(&schema, &["tree"]));
    assert!(text(&o).contains("cable 1.0.0 (registry)"), "{}", text(&o));

    // A fresh checkout (packages not committed) installs with --locked, and
    // offline from the cache.
    std::fs::remove_dir_all(schema.join("packages/sfs")).unwrap();
    std::fs::remove_dir_all(schema.join("packages/cable")).unwrap();
    let o = ok(env.fpkg(&schema, &["--offline", "install", "--locked"]));
    assert!(text(&o).contains("2 added"), "{}", text(&o));
    ok(env.fpkg(&schema, &["verify"]));

    // Local edits to an installed package fail verify with exit 4.
    let lib = schema.join("packages/sfs/lib/install.lua");
    std::fs::write(&lib, "-- edited\n").unwrap();
    let o = code(env.fpkg(&schema, &["verify"]), 4);
    assert!(text(&o).contains("sfs was modified after install"), "{}", text(&o));
    // install notices the edit and reinstalls ("repaired"); the lock is not stale.
    let o = ok(env.fpkg(&schema, &["install", "--locked"]));
    assert!(text(&o).contains("Repairing") && text(&o).contains("1 repaired"), "{}", text(&o));
    ok(env.fpkg(&schema, &["verify"]));
    // verify sees every file, also those that packing would leave out.
    for extra in ["packages/sfs/cache.db", "packages/sfs/.DS_Store", "packages/sfs/lib/node_modules/x.js"] {
        let p = schema.join(extra);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(&p, "extra").unwrap();
        let o = code(env.fpkg(&schema, &["verify"]), 4);
        assert!(text(&o).contains("sfs was modified after install"), "{extra}: {}", text(&o));
        std::fs::remove_file(&p).unwrap();
    }
    ok(env.fpkg(&schema, &["verify"]));
    // A missing file too.
    std::fs::remove_file(schema.join("packages/sfs/lib/install.lua")).unwrap();
    code(env.fpkg(&schema, &["verify"]), 4);
    ok(env.fpkg(&schema, &["install", "--locked"]));
    ok(env.fpkg(&schema, &["verify"]));
    // check skips installed packages unless --all.
    let o = ok(env.fpkg(&schema, &["--json", "check"]));
    assert_eq!(json(&o).as_array().unwrap().len(), 1, "{}", text(&o));
    let o = ok(env.fpkg(&schema, &["--json", "check", "--all"]));
    assert_eq!(json(&o).as_array().unwrap().len(), 3, "{}", text(&o));

    // An unmarked copy of a locked registry package is a conflict (exit 2);
    // --force replaces it.
    std::fs::remove_file(schema.join("packages/cable/.fpkg.toml")).unwrap();
    let o = code(env.fpkg(&schema, &["install"]), 2);
    assert!(text(&o).contains("packages/cable exists without an .fpkg.toml marker but is locked"), "{}", text(&o));
    let o = ok(env.fpkg(&schema, &["install", "--force"]));
    assert!(text(&o).contains("1 added"), "{}", text(&o));
    ok(env.fpkg(&schema, &["verify"]));

    // A stale lock fails --locked with exit 3.
    let s = read(&spec).replace("s.depends('sfs', '~> 7.0')", "s.depends('sfs', '~> 8.0')");
    std::fs::write(&spec, &s).unwrap();
    let o = code(env.fpkg(&schema, &["install", "--locked"]), 3);
    assert!(text(&o).contains("stale"), "{}", text(&o));
    let o = code(env.fpkg(&schema, &["install"]), 1);
    assert!(text(&o).contains("sfs ~> 8.0"), "{}", text(&o));
    std::fs::write(&spec, s.replace("'~> 8.0'", "'~> 7.0'")).unwrap();

    // add and remove edit the manifest, lock and install.
    let o = ok(env.fpkg(&schema, &["add", "yaml"]));
    assert!(text(&o).contains("Adding"), "{}", text(&o));
    assert!(read(&spec).contains("  s.depends('yaml', '~> 1.2')\n"), "{}", read(&spec));
    assert!(schema.join("packages/yaml/.fpkg.toml").is_file());
    code(env.fpkg(&schema, &["add", "yaml"]), 1);
    // A failed resolution leaves the manifest and the lock as they were.
    let (before_spec, before_lock) = (read(&spec), read(&schema.join("fpkg.lock")));
    let o = code(env.fpkg(&schema, &["add", "tween@~> 99.0"]), 1);
    assert!(text(&o).contains("tween"), "{}", text(&o));
    let o = code(env.fpkg(&schema, &["add", "no_such_package@1.0.0"]), 1);
    assert!(text(&o).contains("no_such_package"), "{}", text(&o));
    assert_eq!(read(&spec), before_spec);
    assert_eq!(read(&schema.join("fpkg.lock")), before_lock);
    ok(env.fpkg(&schema, &["remove", "yaml"]));
    assert!(!read(&spec).contains("yaml"));
    assert!(!schema.join("packages/yaml").exists(), "remove uninstalls");
    ok(env.fpkg(&schema, &["verify"]));
    // A manifest fpkg cannot edit safely: exit 2 with the line to add.
    let guarded = read(&spec).replace("  s.depends 'cable'\n", "  if IS_DEVELOPMENT then\n    s.depends 'cable'\n  end\n");
    std::fs::write(&spec, &guarded).unwrap();
    let o = code(env.fpkg(&schema, &["add", "tween"]), 2);
    assert!(text(&o).contains("s.depends('tween', '~> 2.1')"), "{}", text(&o));
    assert_eq!(read(&spec), guarded, "the manifest is untouched");
    std::fs::write(&spec, guarded.replace("  if IS_DEVELOPMENT then\n    s.depends 'cable'\n  end\n", "  s.depends 'cable'\n")).unwrap();

    // Yank: the lock keeps working; new resolutions skip the version.
    ok(env.fpkg(&flux, &["yank", "sfs@7.0.9"]));
    ok(env.fpkg(&schema, &["install", "--locked"]));
    ok(env.fpkg(&schema, &["verify"]));
    std::fs::remove_file(schema.join("fpkg.lock")).unwrap();
    code(env.fpkg(&schema, &["install"]), 1);
    ok(env.fpkg(&flux, &["yank", "sfs@7.0.9", "--undo"]));
    ok(env.fpkg(&schema, &["update"]));
    ok(env.fpkg(&schema, &["install", "--locked"]));

    // Mirror the lock's packages and install from the mirror.
    let mirror = env.root.join("mirror");
    ok(env.fpkg(&schema, &["mirror", &env.registry_url(), mirror.to_str().unwrap()]));
    assert!(mirror.join("packages/sfs/versions/7.0.9/archive.zip").is_file());
    std::fs::remove_dir_all(schema.join("packages/sfs")).unwrap();
    let mirror_url = format!("file://{}/", mirror.display());
    ok(env.fpkg(&schema, &["--registry", &mirror_url, "install", "--locked"]));
    ok(env.fpkg(&schema, &["verify"]));

    // docs and cache.
    let o = ok(env.fpkg(&schema, &["--json", "cache", "dir"]));
    assert_eq!(json(&o)["dir"], env.root.join("cache").display().to_string());
    code(env.fpkg(&schema, &["--json", "docs", "sfs"]), 1);
    ok(env.fpkg(&schema, &["cache", "clean"]));
    assert!(!env.root.join("cache").exists());
}

#[test]
fn cli_over_http() {
    let env = Env::new();
    let server = mock_registry::MockRegistry::start(&env.root.join("http-registry"), "luna", "fpk_e2e_token");
    let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/flux-ce");
    let flux = env.root.join("flux-ce");
    copy_dir(&fixtures, &flux);
    let url = server.url.as_str();
    let http = |args: &[&str]| -> Vec<String> {
        let mut v = vec!["--registry".to_string(), url.to_string()];
        v.extend(args.iter().map(|s| s.to_string()));
        v
    };
    let run = |project: &Path, args: &[&str], stdin: Option<&str>| {
        let a = http(args);
        let a: Vec<&str> = a.iter().map(String::as_str).collect();
        env.fpkg_with(project, &a, &[], stdin)
    };

    // Not logged in: publishing needs a token.
    let o = code(run(&flux, &["publish", "sfs", "--yes"], None), 1);
    assert!(text(&o).contains("fpkg login"), "{}", text(&o));
    // A rejected token is not stored.
    let o = code(run(&flux, &["login"], Some("fpk_wrong\n")), 1);
    assert!(text(&o).contains("did not accept the token"), "{}", text(&o));
    let o = ok(run(&flux, &["login"], Some("fpk_e2e_token\n")));
    assert!(text(&o).contains("as luna"), "{}", text(&o));
    let creds = read(&env.root.join("config/credentials.toml"));
    assert!(creds.contains(&format!("[registries.\"{url}\"]")) && creds.contains("user = \"luna\""), "{creds}");
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = std::fs::metadata(env.root.join("config/credentials.toml")).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o600);
    }

    // publish: refused without confirmation and no terminal; then with --yes.
    let o = code(run(&flux, &["publish", "sfs"], None), 2);
    assert!(text(&o).contains("--yes"), "{}", text(&o));
    let o = ok(run(&flux, &["publish", "sfs", "--yes"], None));
    let out = text(&o);
    assert!(out.contains(&format!("{url}packages/sfs")), "{out}");
    assert!(out.contains(&format!("{url}docs/sfs/7.0.9/")), "{out}");
    // cable depends on sfs, which is now there.
    ok(run(&flux, &["publish", "cable", "--yes"], None));

    let o = ok(run(&flux, &["--json", "search", "cab"], None));
    assert_eq!(json(&o)["packages"][0]["id"], "cable");
    let o = ok(run(&flux, &["--json", "docs", "sfs"], None));
    assert_eq!(json(&o)["url"], format!("{url}docs/sfs/7.0.9/"));
    let o = code(run(&flux, &["owner", "add", "sfs", "nobody_here"], None), 1);
    assert!(text(&o).contains("404"), "{}", text(&o));
    let o = ok(run(&flux, &["--json", "owner", "list", "sfs"], None));
    assert_eq!(json(&o), serde_json::json!(["luna"]));

    // A schema installs over HTTP.
    let schema = env.root.join("schema");
    std::fs::create_dir_all(schema.join("packages")).unwrap();
    std::fs::write(schema.join("packagespec.lua"), "Package:describe(function(s)\n  s.name = 'Schema'\n  s.version = '0.1.0'\n  s.depends 'cable'\nend)\n").unwrap();
    let o = ok(run(&schema, &["install"], None));
    assert!(text(&o).contains("2 added"), "{}", text(&o));
    assert!(read(&schema.join("fpkg.lock")).contains(&format!("source = \"registry+{url}\"")));
    ok(run(&schema, &["verify"], None));
    ok(run(&schema, &["--json", "info", "sfs@7.0.9"], None));

    // Yank needs the token too; logout removes it, FPKG_TOKEN still works.
    ok(run(&flux, &["yank", "cable@1.0.0"], None));
    ok(run(&flux, &["logout"], None));
    assert!(!read(&env.root.join("config/credentials.toml")).contains("fpk_e2e_token"));
    code(run(&flux, &["yank", "cable@1.0.0", "--undo"], None), 1);
    let a = http(&["yank", "cable@1.0.0", "--undo"]);
    let a: Vec<&str> = a.iter().map(String::as_str).collect();
    ok(env.fpkg_with(&flux, &a, &[("FPKG_TOKEN", "fpk_e2e_token")], None));

    // Plain HTTP is for loopback only.
    let o = code(env.fpkg(&flux, &["--registry", "http://example.com/", "login"]), 1);
    assert!(text(&o).contains("plain http"), "{}", text(&o));
}
